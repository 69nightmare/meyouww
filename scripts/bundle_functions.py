#!/usr/bin/env python3
"""Inlines supabase/functions/_shared into one file per Edge Function.

The Supabase dashboard editor deploys a single file, so each function in
supabase/bundled/ contains its shared helpers inline. The CLI and the "Deploy
backend" workflow deploy the normal multi-file sources instead; both are the
same code. CI re-runs this script and fails if the bundles are out of date.

    python3 scripts/bundle_functions.py          # write bundles
    python3 scripts/bundle_functions.py --check  # fail if bundles are stale
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FUNCTIONS = ROOT / "supabase" / "functions"
OUT = ROOT / "supabase" / "bundled"
SHARED_IMPORT = re.compile(r'^import\s+\{([^}]*)\}\s+from\s+"\.\./_shared/([a-z_]+)\.ts";\s*$', re.M)
LOCAL_IMPORT = re.compile(r'^import\s+\{([^}]*)\}\s+from\s+"\./([a-z_]+)\.ts";\s*$', re.M)
EXTERNAL_IMPORT = re.compile(r'^import\s+.*\s+from\s+"(jsr:|npm:|https:).*";\s*$', re.M)


def shared_module(name: str, seen: set, externals: list) -> str:
    if name in seen:
        return ""
    seen.add(name)
    src = (FUNCTIONS / "_shared" / f"{name}.ts").read_text(encoding="utf-8")
    parts = []
    for m in LOCAL_IMPORT.finditer(src):
        parts.append(shared_module(m.group(2), seen, externals))
    src = LOCAL_IMPORT.sub("", src)
    for m in EXTERNAL_IMPORT.finditer(src):
        if m.group(0) not in externals:
            externals.append(m.group(0))
    src = EXTERNAL_IMPORT.sub("", src)
    src = re.sub(r"^export\s+(?=(async\s+)?function|const|let|interface|type|class)", "", src, flags=re.M)
    parts.append(f"// ---- _shared/{name}.ts ----\n{src.strip()}\n")
    return "\n".join(p for p in parts if p)


def bundle(fn: str) -> str:
    src = (FUNCTIONS / fn / "index.ts").read_text(encoding="utf-8")
    seen: set = set()
    externals: list = []
    shared = [shared_module(m.group(2), seen, externals) for m in SHARED_IMPORT.finditer(src)]
    body = SHARED_IMPORT.sub("", src)
    for m in EXTERNAL_IMPORT.finditer(body):
        if m.group(0) not in externals:
            externals.append(m.group(0))
    body = EXTERNAL_IMPORT.sub("", body)
    header = (
        f"// GENERATED by scripts/bundle_functions.py from supabase/functions/{fn}. Do not edit.\n"
        "// Single-file version for the Supabase dashboard editor.\n"
    )
    return header + "\n".join(externals) + "\n\n" + "\n".join(s for s in shared if s) + f"\n// ---- {fn}/index.ts ----\n" + body.strip() + "\n"


def main() -> int:
    check = "--check" in sys.argv
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for d in sorted(p for p in FUNCTIONS.iterdir() if p.is_dir() and not p.name.startswith("_")):
        text = bundle(d.name)
        target = OUT / f"{d.name}.ts"
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(target.name)
        else:
            target.write_text(text, encoding="utf-8")
            print(f"wrote {target.relative_to(ROOT)} ({len(text)} chars)")
    if stale:
        print("Out of date, run scripts/bundle_functions.py:", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
